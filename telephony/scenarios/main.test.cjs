const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')

const src = fs.readFileSync(path.join(__dirname, 'main.js'), 'utf8')
const start = src.indexOf('function classifyDestination')
assert.ok(start > 0, 'helpers missing in main.js')
const helpers = {}
vm.runInNewContext(
  src.slice(start) +
    [
      '',
      'this.classifyDestination = classifyDestination',
      'this.toDigits = toDigits',
      'this.toE164 = toE164',
    ].join('\n'),
  helpers,
)

